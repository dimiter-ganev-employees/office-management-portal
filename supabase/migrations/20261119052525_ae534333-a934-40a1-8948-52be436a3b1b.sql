CREATE TABLE public.revisions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id integer NOT NULL REFERENCES public.problems(id),
  amount numeric(12,2) NOT NULL,
  revision_date date NOT NULL DEFAULT CURRENT_DATE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.revisions TO anon, authenticated;
GRANT ALL ON public.revisions TO service_role;
ALTER TABLE public.revisions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Anyone can view revisions" ON public.revisions FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Anyone can add revisions" ON public.revisions FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "Anyone can edit revisions" ON public.revisions FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Anyone can delete revisions" ON public.revisions FOR DELETE TO anon, authenticated USING (true);
CREATE TRIGGER update_revisions_updated_at BEFORE UPDATE ON public.revisions FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();