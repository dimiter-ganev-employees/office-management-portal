CREATE TABLE public.problems (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  comment text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.problems TO anon, authenticated;
GRANT ALL ON public.problems TO service_role;
ALTER TABLE public.problems ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Anyone can view problems" ON public.problems FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Anyone can add problems" ON public.problems FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "Anyone can edit problems" ON public.problems FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Anyone can delete problems" ON public.problems FOR DELETE TO anon, authenticated USING (true);
CREATE TRIGGER update_problems_updated_at BEFORE UPDATE ON public.problems FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();